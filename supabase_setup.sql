-- 1. Crear la tabla de mediciones y capturas si no existe
CREATE TABLE IF NOT EXISTS public.mediciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('America/Argentina/Buenos_Aires', NOW()),
    contador INT NOT NULL DEFAULT 0,
    tipo_evento TEXT NOT NULL DEFAULT 'captura_cogollera',
    temperatura NUMERIC(5,2),
    sensor1 INT,
    sensor2 INT
);

-- 2. Si la tabla ya existía de pruebas anteriores, añadimos las nuevas columnas
ALTER TABLE public.mediciones ADD COLUMN IF NOT EXISTS tipo_evento TEXT DEFAULT 'captura_cogollera';
ALTER TABLE public.mediciones ADD COLUMN IF NOT EXISTS sensor1 INT;
ALTER TABLE public.mediciones ADD COLUMN IF NOT EXISTS sensor2 INT;

-- 3. Habilitar Seguridad por Fila (Row Level Security - RLS)
ALTER TABLE public.mediciones ENABLE ROW LEVEL SECURITY;

-- 4. Políticas para permitir lecturas y escrituras anónimas (con la API Key pública)
DROP POLICY IF EXISTS "Permitir insercion anonima desde ESP32" ON public.mediciones;
CREATE POLICY "Permitir insercion anonima desde ESP32"
ON public.mediciones
FOR INSERT
TO anon
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir lectura publica para panel web" ON public.mediciones;
CREATE POLICY "Permitir lectura publica para panel web"
ON public.mediciones
FOR SELECT
TO anon
USING (true);

-- 5. Activar Supabase Realtime para que la web se actualice sola al instante
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND tablename = 'mediciones'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.mediciones;
    END IF;
END $$;

-- 6. Índices para consultas rápidas por fecha y evento
CREATE INDEX IF NOT EXISTS idx_mediciones_created_at ON public.mediciones(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_mediciones_tipo_evento ON public.mediciones(tipo_evento);

-- Confirmación visual
COMMENT ON TABLE public.mediciones IS 'Registro de capturas de cogollera y telemetria del sensor ESP32';

